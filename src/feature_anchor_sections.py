"""Independent, measured test-anchor views and their calibration-only controls.

Photographic plots stay local. Every section probes clean inputs only, for both
Standard and PGD-trained models. PGD describes the latter model's training, not
an attack generated by these views; this is not a robustness evaluation.
"""

